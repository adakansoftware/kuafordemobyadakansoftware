export function getAdminMessages(locale: Locale): AdminMessages {
  return locale === "en" ? (adminMessages.en as AdminMessages) : (adminMessages.tr as AdminMessages)
}

export function formatAdminMessage(template: string, params?: MessageParams) {
  if (!params) {
    return template
  }

  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match
  )
}
